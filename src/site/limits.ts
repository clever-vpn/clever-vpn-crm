/**
 * 站点体积上限：**唯一口径 = 整版字节**（文本 + 素材一起算）。
 *
 * 契约 `site-studio.md` §4.4 / 标准 `site-template.md` §3：这是**契约常量**，
 * 由 `/api/site/meta` 的 `limits` 对外发布，studio 与 CRM 都读这一份。
 *
 * 为什么是"整版"：原来两边的数不是一个口径 —— studio 的 8 MB 只数文本、CRM 的
 * 32 MB 数整版。做同一件事的两个上限，图片多一点的站会在一侧撞墙、在另一侧放行，
 * 看的人只会以为"改了一个没改完"。素材单张就允许 2 MB，所以总量必须按整版算。
 *
 * 写在这里而不是 `publish.ts` / `source.ts` 里：三处校验（源包、产物、meta）
 * 必须同一个数，分开写就是三份会漂移的常量。
 */
export const SITE_LIMITS = {
  /** 单个文件（文本或素材） */
  fileBytes: 2 << 20,
  /** 一版整包总大小（文本 + 素材） */
  totalBytes: 32 << 20,
  /** 一版最多几个文件（页数不设限，但总量有工程上限） */
  files: 200,
} as const;
